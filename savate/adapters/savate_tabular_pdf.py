def _brief(error):
    """One line of an exception. poppler answers a non-PDF with hundreds."""
    text = " ".join(str(error).split())
    return text if len(text) <= 160 else text[:157] + "..."


def read(source, slug, meta=None, **options):
    """(Tournament, [Placing], Report) from one column-headed results table."""
    from savate import sources

    meta = meta or {}
    report = Report(source=str(source), adapter=NAME)
    tournament = Tournament(
        slug=slug, name=meta.get("name", slug),
        discipline=meta.get("discipline", ""), level=meta.get("level", ""),
        format=meta.get("format", ""), age_class=meta.get("age_class", ""),
        year=meta.get("year", ""), city=meta.get("city", ""),
        country=meta.get("country", ""),
        source=str(source), adapter=NAME)

    try:
        path = sources.fetch_archived(str(source)) if options.get("archived") \
            else sources.fetch(source, refresh=options.get("refresh", False))
    except Exception as e:
        report.problem(f"the document could not be fetched: {_brief(e)}")
        return tournament, [], report

    try:
        words = pdf.words(path)
    except Exception as e:
        report.problem(f"the document could not be read as a PDF: {_brief(e)}")
        return tournament, [], report

    report.read = len({w.page for w in words})
    lines = pdf.rows(words)
    kinds = [k for k in (_header_kind(pdf.text_of(l)) for l in lines) if k]
    if not kinds:
        report.problem("no column header this adapter recognises - the sheet "
                       "is not one of the four it reads")
        return tournament, [], report
    kind = kinds[0]
    report.notes["layout"] = kind

    beyond_podium, repeats, codes = 0, [], []
    try:
        if kind == "icebits":
            placings, beyond_podium, repeats = _read_icebits(
                lines, slug, report)
        elif kind == "izvjestaj":
            placings, beyond_podium = _read_izvjestaj(lines, slug, report)
        elif kind == "fisav":
            placings, beyond_podium, codes = _read_fisav(
                lines, slug, meta, report)
        else:
            placings, beyond_podium = _read_sportu(lines, slug, meta, report)
    except Exception as e:
        # A malformed sheet is a report, not a traceback. Whatever was read
        # before the failure is lost rather than half-kept, because a partial
        # table cannot be told from a complete one after the fact.
        report.problem(f"the {kind} table could not be read: "
                       f"{type(e).__name__}: {_brief(e)}")
        return tournament, [], report

    report.notes["placings"] = len(placings)
    if beyond_podium:
        report.notes["beyond_podium"] = beyond_podium
        report.problem(
            f"{beyond_podium} competitor(s) are placed 4th or lower on this "
            f"sheet and are not kept: schema.Placing is a podium place and "
            f"check_placing admits ranks 1-3 only")
    if repeats:
        report.notes["repeated_sections"] = [" ".join(k).strip()
                                             for k in repeats]
        report.problem(
            "age section(s) " +
            ", ".join(sorted({" ".join(k).strip() for k in repeats})) +
            " are opened twice in one document - these sheets cover two "
            "disciplines and label neither block - so the later block's "
            "categories are suffixed '(block N)'")
    if codes:
        report.notes["country_codes"] = codes
    if not placings:
        report.problem(f"the {kind} header was found but no placing was read "
                       f"under it")
    return tournament, placings, report
